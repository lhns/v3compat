#!/usr/bin/env python3
"""Builds src/allowlist.inc and docs/allowlist.md from the evidence in test/allow/evidence.

gen.py build                 regenerate both from the committed evidence
gen.py check PROBE KEYS      CI: both are up to date, DR still decodes every row to its key, and
                             this CPU's PROBE matches the Ivy Bridge results on every tested row
"""
import gzip
import pathlib
import sys
from collections import Counter, defaultdict

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
EV = HERE / "evidence"
INC = ROOT / "src" / "allowlist.inc"
DOC = ROOT / "docs" / "allowlist.md"
C_N = "7"  # enum cls in src/allow.h: not one of the classes the CPU lacks
ALL_FAULT = "1f"


def lines(path):
    with gzip.open(path, "rt", newline="\n") as f:
        return [l.rstrip("\n") for l in f]


def table(path):
    return [l.split("\t") for l in lines(path) if not l.startswith("#")]


def cpu_of(path):
    return lines(path)[0].removeprefix("#cpu ")


def policy():
    p = {}
    for l in (HERE / "policy.tsv").read_text().splitlines():
        if l and not l.startswith("#"):
            iclass, kind, why = l.split("\t")
            p[iclass] = (kind, why)
    return p


def status(r, pol, emulated):
    """What the evidence says of one row: 'native*', 'emulated', or a reason it is refused."""
    if r["key"] == "-":
        return "dr-invalid"
    if r["cls"] != C_N:
        return "emulated" if r["iform"] in emulated else "lacked-not-in-emulation-suite"
    kind, _ = pol.get(r["iclass"], (None, None))
    if r["notrun"] != "-":
        return "native-untested" if kind == "untested" else "excluded:" + r["notrun"]
    if r["ivb"] != "same" and kind != "hint":
        return "decodes-differently" if r["ivb"].startswith("as:") else "not-on-ivy-bridge"
    if r["isig"] == "ff":
        return "killed-harness"
    if r["isig"] != r["asig"] or r["ih"] != r["ah"]:
        return "ivy-faults" if r["isig"] == ALL_FAULT else "differs-on-avx2"
    if r["isig"] == ALL_FAULT:
        return "native-faults" if kind == "faults" else "faults-on-both"
    return "native-tested"


def load():
    rows = table(EV / "rows.tsv.gz")
    keys = table(EV / "keys.tsv.gz")
    ivb = table(EV / "ivybridge.tsv.gz")
    avx2 = table(EV / "avx2.tsv.gz")
    assert len(rows) == len(keys) == len(ivb) == len(avx2), "evidence files out of step"
    pol = policy()
    emu = {l for l in (HERE / "emulated-iforms.txt").read_text().splitlines() if not l.startswith("#")}
    out = []
    for r, k, i, a in zip(rows, keys, ivb, avx2):
        d = dict(hex=r[0], iform=r[2], iclass=r[3], isa=r[4], ivb=r[5], notrun=r[6], key=k[0], cls=k[1], text=k[2],
                 isig=i[0], ih=i[1], asig=a[0], ah=a[1])
        d["st"] = status(d, pol, emu)
        out.append(d)
    return out, pol


def decide(rows):
    """A key is listed only if every row reaching it is: one bad form refuses the whole shape."""
    by_key = defaultdict(list)
    for r in rows:
        if r["key"] != "-":
            by_key[r["key"]].append(r)
    native, emulated, mixed = {}, {}, []
    for k, rs in by_key.items():
        sts = {r["st"] for r in rs}
        if sts <= {"native-tested", "native-faults", "native-untested"}:
            native[k] = rs[0]["text"]
        elif sts == {"emulated"}:
            emulated[k] = rs[0]["text"]
        elif any(s.startswith("native") or s == "emulated" for s in sts):
            mixed.append((rs[0]["text"], sorted({r["iclass"] + ":" + r["st"] for r in rs})))
    return native, emulated, mixed


def inc_text(native, emulated):
    out = ["/* Generated by test/allow/gen.py from test/allow/evidence; see docs/allowlist.md. Do not edit. */"]
    for name, t in (("allow_native", native), ("allow_emulated", emulated)):
        out.append(f"static const uint64 {name}[] = {{")
        out += [f"    0x{k}ULL, /* {t[k]} */" for k in sorted(t)]
        out.append("};")
    return "\n".join(out) + "\n"


def doc_text(rows, pol, native, emulated, mixed):
    forms = len({r["iform"] for r in rows})
    per = Counter(r["st"] for r in rows)
    iforms = table(EV / "iforms.tsv.gz")
    reached = {r["iform"] for r in rows}
    unreached = Counter(isa for f, isa in iforms if f not in reached)
    o = ["# Audited instruction list", "",
         "Generated by `test/allow/gen.py`; regenerate with `test/allow/regen.sh` (see its header). Do not edit.", "",
         "A key is DR opcode, encoding bits and operand classes (`src/allow.c`). Native keys run as they are, emulated",
         "keys go through the expansions, and anything else exits with status 86 if executed (ADR 0008).", "",
         f"- Ivy Bridge evidence: `{cpu_of(EV / 'ivybridge.tsv.gz')}`",
         f"- AVX2 evidence: `{cpu_of(EV / 'avx2.tsv.gz')}`",
         f"- Universe: {len(rows)} test rows, {forms} XED iforms reached of {len(iforms)} in XED's tables.",
         f"- Listed: {len(native)} native keys, {len(emulated)} emulated keys.", "",
         "## Rows by outcome", "", "| Outcome | Rows |", "|---|---|"]
    o += [f"| {k} | {v} |" for k, v in sorted(per.items())]
    o += ["", "## Iforms never reached by the sweep, by ISA set: all refused", "",
          "EVEX is refused as a class, so these need no row. Others need bytes the sweep does not try.", "", "| ISA set | Iforms |", "|---|---|"]
    evex = sum(v for k, v in unreached.items() if "AVX512" in k or "AVX10" in k or "APX" in k or "KNC" in k)
    o.append(f"| AVX-512, AVX10, APX, KNC | {evex} |")
    o += [f"| {k} | {v} |" for k, v in sorted(unreached.items()) if not ("AVX512" in k or "AVX10" in k or "APX" in k or "KNC" in k)]

    def classes(st):
        return ", ".join(f"`{c.lower()}`" for c in sorted({r["iclass"] for r in rows if r["st"] == st}))

    o += ["", "## Encodings that decode as something else on Ivy Bridge", "",
          "XED's Ivy Bridge tables against its full ones. Each either is emulated, stays a hint (policy below), or is refused.", "",
          "| Instruction | On Ivy Bridge | Ran on the CPU | Outcome |", "|---|---|---|---|"]
    silent = defaultdict(set)
    for r in rows:
        if r["ivb"].startswith("as:"):
            silent[(r["iclass"], r["ivb"][3:])].add((r["isig"] != ALL_FAULT, r["st"]))
    for (c, a), v in sorted(silent.items()):
        ran = "yes" if any(x[0] for x in v) else "no"
        o.append(f"| `{c.lower()}` | `{a.lower()}` | {ran} | {', '.join(sorted(x[1] for x in v))} |")
    ran_ud = sorted({r["iclass"].lower() for r in rows if r["ivb"] == "ud" and r["isig"] not in (ALL_FAULT, "-", "ff") and r["st"] != "emulated"})
    o += ["", "## Not on Ivy Bridge by XED's tables, yet the CPU did not fault on every seed", "",
          "Refused unless policy says it is a hint: " + ", ".join(f"`{c}`" for c in ran_ud), "",
          "## Policy: listed against the default rule", "", "| Instruction | Kind | Why |", "|---|---|---|"]
    o += [f"| `{c.lower()}` | {k} | {w} |" for c, (k, w) in sorted(pol.items())]
    o += ["", "## Excluded from testing, so refused unless policy lists them", ""]
    for st in sorted(k for k in per if k.startswith("excluded:")):
        o.append(f"- **{st[9:]}**: {classes(st)}")
    o += ["", "## Refused because the machines differ", "", classes("differs-on-avx2") or "None.", "",
          "## Keys with a refused form among listed ones: the whole key is refused", ""]
    o += [f"- `{t}`: {', '.join(s)}" for t, s in sorted(mixed)] or ["None."]
    o += ["", "## Unverified", "",
          "The AVX2 evidence is not Intel AVX2 hardware, as those references are not approved. So a native key means Ivy",
          "Bridge and that CPU agree on these seeds, and Intel AVX2 silicon is assumed to as well. That matters most where",
          "vendors are known to diverge: NaN priority, undefined outputs the SDM leaves open. Forms listed as `untested`",
          "above carry no differential evidence at all. Five seed states are strong evidence, not proof (ADR 0001).", "",
          "The Ivy Bridge evidence comes from a KVM guest: what the hypervisor intercepts is seen as it presents it.", "",
          "`allowlist-check` compares each runner with the Ivy Bridge results on every listed form, and runners vary in",
          "CPU model. A failure there is a real disagreement, not a flake: rerun `regen.sh` with that run's `allow-probe`",
          "artifact, which makes the list stricter.", "",
          "On hosts with more features, `cpuid` leaves still passed through (1, 0xD.0, 0x80000001 EDX, 0x80000007/8) could",
          "steer a program to a form the list refuses. That exits 86, cleanly, and only CI's AMD runners have tried it.", ""]
    return "\n".join(o)


def build():
    rows, pol = load()
    native, emulated, mixed = decide(rows)
    return inc_text(native, emulated), doc_text(rows, pol, native, emulated, mixed), rows, native


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("build", "check"):
        sys.exit(__doc__)
    inc, doc, rows, native = build()
    if sys.argv[1] == "build":
        INC.write_text(inc, newline="\n")
        DOC.write_text(doc, newline="\n")
        print(f"{len(native)} native keys; {Counter(r['st'] for r in rows)}")
        return
    bad = 0
    if INC.read_text() != inc or DOC.read_text() != doc:
        print("allowlist.inc or allowlist.md is not what the evidence gives: run gen.py build")
        bad += 1
    fresh_keys = [l.split("\t")[0] for l in pathlib.Path(sys.argv[3]).read_text().splitlines()]
    drifted = [r["hex"] for r, k in zip(rows, fresh_keys) if r["key"] != k]
    if drifted or len(fresh_keys) != len(rows):
        print(f"DR decodes {len(drifted)} rows to another key, e.g. {drifted[:5]}: rerun regen.sh")
        bad += 1
    text = pathlib.Path(sys.argv[2]).read_text().splitlines()
    print("this CPU:", text[0], "; committed AVX2 evidence:", cpu_of(EV / "avx2.tsv.gz"))
    fresh = [l.split("\t") for l in text[1:]]
    if len(fresh) != len(rows):
        print("probe row count differs")
        bad += 1
    else:
        diff = [r for r, f in zip(rows, fresh) if r["st"] == "native-tested" and (r["isig"], r["ih"]) != (f[0], f[1])]
        for r in diff[:30]:
            print("differs here:", r["hex"], r["iform"], r["text"])
        bad += bool(diff)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
